package ch.eitchnet.pi4j.oled.fonts;

/**
 * This font implements a 3x5 pixel character set to write text to the SH1106 OLED Display
 *
 * @author Roland Baudouin
 */
public class DotMatrixFont3x5 extends DotMatrixFont {
	private static final int fontWidth = 3;
	private static final int fontHeight = 5;
	private static final int spaceWidth = 2;
	private static final int bytesPerChar = 3;
	private static final byte startChar = 0x41;
	private static final byte stopChar = 0x5A;
	private static final FONT_SCAN_MODE scanMode = FONT_SCAN_MODE.FONT_SCAN_V;

	private static final byte[] array = {
			0x1E, 0x05, 0x1E,    //A
			0x1F, 0x15, 0x0A,
			0x0E, 0x11, 0x11,
			0x1F, 0x11, 0x0E,
			0x1F, 0x15, 0x11,
			0x1F, 0x05, 0x01,
			0x0E, 0x11, 0x1D,
			0x1F, 0x04, 0x1F,
			0x11, 0x1F, 0x11,
			0x08, 0x10, 0x0F,
			0x1F, 0x04, 0x1B,
			0x1F, 0x10, 0x10,
			0x1F, 0x02, 0x1F,
			0x1E, 0x04, 0x0F,
			0x0E, 0x11, 0x0E,
			0x1F, 0x05, 0x02,
			0x0E, 0x19, 0x1E,
			0x1F, 0x05, 0x1A,
			0x12, 0x15, 0x09,
			0x01, 0x1F, 0x01,
			0x1F, 0x10, 0x1F,
			0x0F, 0x10, 0x0F,
			0x1F, 0x08, 0x1F,
			0x1B, 0x04, 0x1B,
			0x03, 0x1C, 0x03,
			0x19, 0x15, 0x13    //Z
	};

	public DotMatrixFont3x5() {
		super(fontWidth, fontHeight, spaceWidth, startChar, stopChar, bytesPerChar, array, scanMode);
	}
}
